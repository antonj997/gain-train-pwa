export const catalogue: CatalogueExercise[] = rows.map(
  ([name, category, equipment, aliases, options]) => ({
    id: "builtin:" + name.toLowerCase().replaceAll(" ", "-"),
    name,
    category,
    equipment,
    aliases: aliases.split(";").map((alias) => alias.trim()),
    load:
      options?.load ?? (equipment === "bodyweight" ? "bodyweight" : "weight"),
    measure: options?.measure ?? "reps",
  }),
);

export const catalogueById = new Map(catalogue.map((e) => [e.id, e]));
