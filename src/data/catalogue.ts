export type CatalogueExercise = {
  /** "builtin:" plus the lower-case name with dashes. Records refer to it, so it never changes. */
  id: string;
  name: string;
  category: string;
  equipment: Equipment;
  /** Short and Swedish names people search by. */
  aliases: string[];
  /** The load and measure a new set starts with. */
  load: "weight" | "bodyweight" | "assisted";
  measure: "reps" | "seconds";
};

